export function buildMyStylePrompt(samples: string[]): string {
  const lines = ["[사용자가 평소 보낸 메시지 예시]"];
  samples.forEach((sample, i) => lines.push(`${i + 1}. ${sample}`));
  lines.push(
    "",
    "위 예시들에서 이름, 장소, 일정, 사건 같은 구체적인 내용은 무시하고 말투 스타일만 추출하라.",
  );
  return lines.join("\n");
}
